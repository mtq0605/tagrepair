#pragma once
// =============================================================================
// 同步标记检测:样本里有没有控制流的同步标记;有的话,开头那条数据同步记录里写的原始采样率是多少
// =============================================================================
// 只做这两件事。不解码、不展开、不渲染,记录里别的字段、别的记录一概不读。
// 下面的格式事实取自公开资料,这里用自己的话写一遍;本文件的实现就是照这一段写的。
//
// 一、控制位在哪
//   载体是两声道的整数 PCM,按 24 bit 样本看(16 bit 的样本当作低 8 位全 0 的 24 bit 样本)。
//   每个立体声帧带一个控制位:左声道样本与右声道样本同一位的异或。是哪一位事先不知道,
//   只知道在 24 bit 样本的第 8 到第 15 位之间(第 0 位是最低位),所以八位都要盯着,先出现同步标记的那一位就是。
//   控制位按时间先后排成一串;多位的字段都是低位先到。
//
// 二、同步标记
//   数据同步记录以固定的 40 位开头:4 位的记录类型(值 5),接着 36 位的常数 0x11319207D。
//   按"先到的是低位"合成一个 40 位的数,就是 0x11319207D5。在某一位的控制位串里看到这 40 位,就算找到了同步标记。
//
// 三、数据同步记录的排布(位的序号从记录的第一位算起)
//      0   40 位   同步标记
//     40    1 位   带不带位置:0 = 这是流的第一条记录;1 = 后面带着一个 32 位的位置
//     41    1 位   不用
//     42    5 位   原始采样率的码          ← 只读这一个字段
//     47    5 位   载体采样率的码
//     52   21 位   别的字段(5、2、2、4、4、4 位),这里不读
//     73    7 位   附加项的个数 N
//     80   N×8 位  每个附加项的长度(位)
//           N×8 位  每个附加项的类型
//          32 位   这条记录在控制流里的位置(第 40 位是 1 时才有)
//                  各个附加项,一个接一个,每个占它自己写明的长度
//           4 位   校验
//
// 四、校验
//   一个 32 位的寄存器,初值是这条记录在控制流里的位置的低 4 位(流的第一条记录位置是 0)。
//   记录的每一位依次进寄存器:先记下寄存器的最低位,寄存器右移一位,新来的这一位放到最高位;
//   记下的那一位是 1 的话,寄存器再异或 3。校验字段之前的位全部进完之后,继续进 0,直到进过的位数是 32 的整数倍;
//   这时寄存器的低 4 位应当等于记录末尾的 4 位校验。
//
// 五、采样率的码(5 位)
//   高 2 位选基准:0 = 44100,1 = 48000,2 = 64000,3 无效;低 3 位是 2 的几次方。采样率 = 基准 × 2^低三位。
//   例:码 3 = 44100 × 8 = 352800;码 10 = 48000 × 4 = 192000。
//
// 这里怎么用上面这些(本程序自己的做法,不是格式规定):
//   八个候选位各记最近 40 个控制位;哪一位先凑出同步标记,就认定是那一位,以后只看它。
//   从标记起收一条记录:头 80 位到齐知道两张表多长,表到齐知道整条多长,整条到齐算校验;
//   校验对上、采样率的码有效,才报采样率,到此为止;否则在同一位上接着找下一个标记。
//   一条记录还没收完、同一位上又出现了标记,前一条作废,从新的标记起重新收。
//   "找到标记"只看标记本身;"读到采样率"必须有一条校验通过的记录。
//
// 样本约定:立体声交错的 int32,24 bit 的值左对齐(FFmpeg 解 24 bit FLAC 得到的 s32 原样就是)。
// =============================================================================
#include <cstddef>
#include <cstdint>
#include <vector>

namespace syncdetect {

constexpr uint64_t kMarker = 0x11319207D5ull;     // 二
constexpr int kMarkerBits = 40;
constexpr int kLowestBit = 8, kHighestBit = 15;   // 一:控制位可能在的那八位(24 bit 样本里的位号)

// 五:采样率的码 → Hz;无效的码返回 0
int rateFromCode(unsigned code);

// 四:bits[0..count) = 一条记录里校验字段之前的全部位(每个元素 0 或 1,先到的在前),position = 记录在控制流里的位置。
// 返回应有的 4 位校验
unsigned recordCheck(const uint8_t* bits, size_t count, uint32_t position);

class Detector {
public:
    // 喂 frames 帧(交错的左、右)。可以分很多次喂,结果与一次喂完相同
    void feed(const int32_t* lr, size_t frames);
    // 看到过同步标记(只看标记本身;记录的校验过没过不影响这一项)
    bool markerFound() const { return bit_ >= 0; }
    // 校验通过的数据同步记录里的原始采样率(Hz);还没读到是 0
    int originalRate() const { return rate_; }
    // 同步标记所在的位(24 bit 样本里的位号 8..15);还没找到是 −1
    int controlBit() const { return bit_ < 0 ? -1 : kLowestBit + bit_; }
    uint64_t framesSeen() const { return frames_; }

private:
    enum class Stage { Search, Head, Table, Body, Done };
    void push(unsigned candidates);               // 一帧的八个候选位(第 i 位 = 样本第 8+i 位的左右异或)
    void decide();                                // 攒够 need_ 位之后走下一步
    unsigned field(size_t at, int width) const;   // 记录里从第 at 位起的 width 位(低位先到)
    void startRecord();
    void searchAgain();

    Stage stage_ = Stage::Search;
    uint64_t recent_[kHighestBit - kLowestBit + 1] = {};   // 每个候选位最近的 40 个控制位,最早的在最低位
    int bit_ = -1;                                // 认定的候选位(0..7);−1 = 还没有
    std::vector<uint8_t> rec_;                    // 正在收的这条记录的位,从同步标记的第一位起
    size_t need_ = 0;                             // rec_ 攒到这么多位再看
    size_t checkAt_ = 0;                          // 校验字段的位号
    int rate_ = 0;
    uint64_t frames_ = 0;
};

} // namespace syncdetect
