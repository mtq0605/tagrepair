#pragma once
// =============================================================================
// 取消:Ctrl+C、Ctrl+Break、关窗口
// =============================================================================
// 约定只有一条:取消只是把一个标志立起来,干活的代码在"停下来不会留下半截东西"的地方自己看它。
//   · 文件与文件之间、只读的阶段(扫描、算指纹、解码、编码到临时文件、核对临时文件):看到就停;
//   · 写文件的那一小段(原地写的那一下;换入已经开始之后):不看,做完这一个文件(或者按原来的安全设计恢复原样)再停。
// 关窗口时系统只给几秒钟:处理函数立起标志之后,等手上这个文件的操作收尾(Busy 在它期间立着)再返回。
// =============================================================================
namespace runctl {

// 装上处理函数(幂等)。之后 Ctrl+C / Ctrl+Break 不再直接结束进程
void install();

bool cancelRequested();
// 自检用:自己立起 / 放下取消标志
void requestCancel();
void resetCancel();

// 一个文件的操作期间立着(可以嵌套)。关窗口的处理函数等到它放下
struct Busy {
    Busy();
    ~Busy();
    Busy(const Busy&) = delete;
    Busy& operator=(const Busy&) = delete;
};

// 测试用的节拍:环境变量 TAGREPAIR_TEST_DELAY_MS 是正数时,每处理一个文件之前等这么多毫秒(上限 5000)。
// 只是变慢;给 tests/ 里"做到一半按 Ctrl+C / 关窗口"的核对一个确定的时机。平时不设这个变量,这里什么都不做
void testPause();

} // namespace runctl
